from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

from .value_objects import (
    SQLDialect,
)


# ==========================================================
# User Question
# ==========================================================

@dataclass(slots=True)
class Question:
    """
    Represents a natural language question received
    from the Query Engine.
    """

    text: str

    user_id: str | None = None

    session_id: str | None = None

    conversation_id: str | None = None

    metadata: dict[str, Any] = field(
        default_factory=dict,
    )

    created_at: datetime = field(
        default_factory=datetime.utcnow,
    )


# ==========================================================
# Generated SQL
# ==========================================================

@dataclass(slots=True)
class SQLQuery:
    """
    SQL query generated by the LLM.
    """

    query: str

    dialect: SQLDialect = SQLDialect.POSTGRESQL

    generated_by: str | None = None

    model: str | None = None

    metadata: dict[str, Any] = field(
        default_factory=dict,
    )

    created_at: datetime = field(
        default_factory=datetime.utcnow,
    )


# ==========================================================
# SQL Execution Result
# ==========================================================

@dataclass(slots=True)
class SQLResult:
    """
    Represents the raw SQL execution result.
    """

    rows: list[dict[str, Any]] = field(
        default_factory=list,
    )

    columns: list[str] = field(
        default_factory=list,
    )

    row_count: int = 0

    execution_time_ms: float | None = None

    metadata: dict[str, Any] = field(
        default_factory=dict,
    )

    created_at: datetime = field(
        default_factory=datetime.utcnow,
    )


# ==========================================================
# Final Response
# ==========================================================

@dataclass(slots=True)
class ChatDatabaseResponse:
    """
    Final response returned by the ChatDatabase module.
    """

    success: bool = True

    answer: str = ""

    sql: str | None = None

    result: SQLResult | None = None

    error: str | None = None

    metadata: dict[str, Any] = field(
        default_factory=dict,
    )

    created_at: datetime = field(
        default_factory=datetime.utcnow,
    )