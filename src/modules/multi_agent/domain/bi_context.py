from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(slots=True)
class BIContext:
    """
    Central execution context for the Multi-Agent BI pipeline.

    The BIContext is the shared state object passed between:
        - Planner
        - TaskExecutor
        - DatabaseTool
        - RAGTool
        - AnalyzerAgent
        - ReporterAgent
        - Memory integration

    Responsibilities:
        1. Preserve the original user request.
        2. Preserve user/session identity.
        3. Store database results.
        4. Store document/RAG context.
        5. Store generated SQL.
        6. Store analysis and final report.
        7. Store tool execution results.
        8. Store sources and metadata.
        9. Collect errors without losing previous state.

    This class does NOT:
        - call the LLM
        - execute SQL
        - retrieve documents
        - perform analysis
        - generate reports

    It only stores and manages execution state.
    """

    # ==========================================================
    # Request Identity
    # ==========================================================

    question: str

    user_id: str | None = None

    session_id: str | None = None

    # ==========================================================
    # Source Selection
    # ==========================================================

    # Possible values:
    # "database"
    # "document"
    # "both"
    # "unknown"
    source_type: str = "unknown"

    # Names of the sources selected/used during execution.
    #
    # Examples:
    # ["database"]
    # ["rag"]
    # ["database", "rag"]
    selected_sources: list[str] = field(
        default_factory=list
    )

    # ==========================================================
    # Memory Context
    # ==========================================================

    # Relevant memories retrieved before planning/execution.
    memory_context: str | None = None

    # ==========================================================
    # Database Results
    # ==========================================================

    # Raw rows returned by DatabaseTool / ChatDatabase.
    raw_data: list[dict[str, Any]] = field(
        default_factory=list
    )

    # SQL generated and executed by the database pipeline.
    sql_query: str | None = None

    # Structured information about the database execution.
    database_result: dict[str, Any] = field(
        default_factory=dict
    )

    # ==========================================================
    # RAG / Document Results
    # ==========================================================

    # Retrieved document context provided by RAG.
    #
    # Kept flexible because the final RAG implementation may
    # return text, structured chunks, or another representation.
    rag_context: Any = None

    # Structured information about RAG execution.
    rag_result: dict[str, Any] = field(
        default_factory=dict
    )

    # ==========================================================
    # Analysis
    # ==========================================================

    # Business insights / KPIs generated by AnalyzerAgent.
    #
    # Kept as str for compatibility with the current AnalyzerAgent.
    analysis_kpis: str | None = None

    # Optional structured analysis output for future extensions.
    analysis_result: dict[str, Any] = field(
        default_factory=dict
    )

    # ==========================================================
    # Visualization
    # ==========================================================

    # Chart configuration generated for the frontend.
    chart_config: dict[str, Any] = field(
        default_factory=dict
    )

    # ==========================================================
    # Final Report
    # ==========================================================

    # Final executive response generated by ReporterAgent.
    final_report: str | None = None

    # ==========================================================
    # Tool Execution State
    # ==========================================================

    # Stores the result of every executed tool.
    #
    # Example:
    #
    # {
    #     "DatabaseTool": {...},
    #     "RAGTool": {...}
    # }
    tool_results: dict[str, Any] = field(
        default_factory=dict
    )

    # ==========================================================
    # Execution State
    # ==========================================================

    success: bool = True

    # Human-readable errors accumulated throughout execution.
    errors: list[str] = field(
        default_factory=list
    )

    # ==========================================================
    # Metadata
    # ==========================================================

    # Cross-cutting metadata that can be populated by any
    # component without changing the core context structure.
    metadata: dict[str, Any] = field(
        default_factory=dict
    )

    # ==========================================================
    # Error Handling
    # ==========================================================

    def add_error(
        self,
        component: str,
        error_msg: str,
    ) -> None:
        """
        Register an execution error.

        The context is immediately marked as unsuccessful,
        while preserving all previously collected state.
        """

        self.success = False

        self.errors.append(
            f"[{component}] {error_msg}"
        )

    # ==========================================================
    # Tool Result Management
    # ==========================================================

    def set_tool_result(
        self,
        tool_name: str,
        result: Any,
    ) -> None:
        """
        Store the result produced by a Tool.

        This allows the Executor and later Agents to inspect
        individual tool outputs without overwriting other data.
        """

        self.tool_results[tool_name] = result

    # ==========================================================
    # Source Management
    # ==========================================================

    def add_source(
        self,
        source_name: str,
    ) -> None:
        """
        Register a source used during execution.

        Duplicate source names are ignored.
        """

        if source_name not in self.selected_sources:
            self.selected_sources.append(
                source_name
            )

    # ==========================================================
    # Database Result Management
    # ==========================================================

    def set_database_result(
        self,
        result: dict[str, Any],
    ) -> None:
        """
        Store structured database execution information.
        """

        self.database_result = result

        self.add_source("database")

        if self.source_type == "unknown":
            self.source_type = "database"

    # ==========================================================
    # RAG Result Management
    # ==========================================================

    def set_rag_result(
        self,
        result: dict[str, Any],
        context: Any = None,
    ) -> None:
        """
        Store structured RAG execution information.
        """

        self.rag_result = result

        if context is not None:
            self.rag_context = context

        self.add_source("rag")

        if self.source_type == "unknown":
            self.source_type = "document"

        elif self.source_type == "database":
            self.source_type = "both"

    # ==========================================================
    # Success State
    # ==========================================================

    def mark_success(self) -> None:
        """
        Mark the context as successfully completed
        when no execution errors exist.
        """

        self.success = len(self.errors) == 0

    # ==========================================================
    # Error State
    # ==========================================================

    def has_errors(self) -> bool:
        """
        Return True when one or more execution errors exist.
        """

        return bool(self.errors)

    # ==========================================================
    # Data Availability
    # ==========================================================

    def has_database_data(self) -> bool:
        """
        Return True when database rows are available.
        """

        return bool(self.raw_data)

    def has_rag_data(self) -> bool:
        """
        Return True when RAG/document context is available.
        """

        if self.rag_context is None:
            return False

        if isinstance(self.rag_context, str):
            return bool(self.rag_context.strip())

        return bool(self.rag_context)

    # ==========================================================
    # Context Summary
    # ==========================================================

    def summary(self) -> dict[str, Any]:
        """
        Return a lightweight summary of the current BI context.

        Useful for logging, debugging, observability, and future
        API responses without exposing the full context.
        """

        return {
            "question": self.question,
            "user_id": self.user_id,
            "session_id": self.session_id,
            "source_type": self.source_type,
            "selected_sources": list(self.selected_sources),
            "has_memory": bool(self.memory_context),
            "database_rows": len(self.raw_data),
            "has_sql": bool(self.sql_query),
            "has_rag": self.has_rag_data(),
            "has_analysis": bool(self.analysis_kpis),
            "has_report": bool(self.final_report),
            "tool_count": len(self.tool_results),
            "success": self.success,
            "error_count": len(self.errors),
        }